#!/usr/bin/env python3
"""How did each committee call pan out?

Usage:
  python3 -I scripts/track_record.py [--out docs/track-record.md]

Reads data/runs.csv (one row per run), downloads daily closes since each run's date for the
ticker and SPY from Yahoo Finance's chart data, and writes a table: price then and now, the
stock's return vs SPY's over the same days, whether the call was right so far, and whether
any price level in the memo (buy_below / exit_below / exit_above) has been hit.

Scoring (so far, not final): BUY is right if the stock beat SPY; PASS is right if it lagged SPY;
WATCH is right if the stock lagged SPY before its trigger was hit (staying out was the right call),
or counts as "triggered" once buy_below is reached. Calls under 30 days old are shown but not scored.
"""
import argparse, csv, json, os, urllib.request
from datetime import date, datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_cache = {}

def daily(sym):
    if sym not in _cache:
        url = f"https://query1.finance.yahoo.com/v8/finance/chart/{sym}?range=5y&interval=1d"
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=30) as r:
            d = json.load(r)["chart"]["result"][0]
        q = d["indicators"]["quote"][0]
        _cache[sym] = [(datetime.fromtimestamp(t, timezone.utc).date(), c, lo, hi)
                       for t, c, lo, hi in zip(d["timestamp"], q["close"], q["low"], q["high"]) if c is not None]
    return _cache[sym]

def since(series, d0):
    return [x for x in series if x[0] >= d0]

def f(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "track-record.md"))
    a = ap.parse_args()
    rows = list(csv.DictReader(open(os.path.join(ROOT, "data", "runs.csv"))))
    spy = daily("SPY")
    lines = ["# Track record", "",
             f"Updated {date.today()} with Yahoo Finance daily closes. Generated by `scripts/track_record.py`; do not edit by hand.", "",
             "| Run | Verdict | Price then | Price now | Stock | SPY | vs SPY | Days | Right so far? | Levels hit | Base value | Review by |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    tally = {}
    for r in rows:
        d0 = date.fromisoformat(r["date"])
        try:
            s = since(daily(r["ticker"]), d0)
        except Exception as e:
            lines.append(f"| {r['run']} | {r['verdict']} | {r['price']} | no data ({type(e).__name__}) | | | | | | | | |")
            continue
        sp = since(spy, d0)
        p0 = f(r["price"]) or (s[0][1] if s else None)
        if not s or not sp or not p0:
            continue
        p1, days = s[-1][1], (s[-1][0] - d0).days
        ret, sret = p1 / p0 - 1, sp[-1][1] / sp[0][1] - 1
        ex = ret - sret
        lo, hi = min(x[2] for x in s if x[2]), max(x[3] for x in s if x[3])
        hits = []
        for k, label, hit in (("buy_below", "buy level", lambda v: lo <= v), ("exit_below", "exit level", lambda v: lo <= v),
                              ("exit_above", "upside level", lambda v: hi >= v)):
            v = f(r.get(k))
            if v and hit(v):
                hits.append(f"{label} ${v:,.2f}")
        v = r["verdict"]
        if days < 30:
            ok = "too early"
        elif v == "BUY":
            ok = "yes" if ex > 0 else "no"
        elif v == "PASS":
            ok = "yes" if ex < 0 else "no"
        elif v == "WATCH":
            ok = "triggered" if any(h.startswith("buy level") for h in hits) else ("yes" if ex < 0 else "no")
        else:
            ok = "n/a"
        tally.setdefault(v, []).append(ok)
        base = f(r.get("value_base"))
        lines.append(f"| {r['run']} | {v} | ${p0:,.2f} | ${p1:,.2f} | {ret:+.1%} | {sret:+.1%} | {ex:+.1%} | {days} | {ok} | "
                     f"{', '.join(hits) or '—'} | {'$%s' % format(base, ',.2f') if base else '—'} | {r.get('review_by') or '—'} |")
    lines += ["", "**Summary** (calls at least 30 days old)", "",
              "| Verdict | Calls | Right | Wrong | Too early |", "|---|---|---|---|---|"]
    for v, oks in sorted(tally.items()):
        lines.append(f"| {v} | {len(oks)} | {sum(o in ('yes',) for o in oks)} | {sum(o == 'no' for o in oks)} | {sum(o == 'too early' for o in oks)} |")
    open(a.out, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))

if __name__ == "__main__":
    main()
